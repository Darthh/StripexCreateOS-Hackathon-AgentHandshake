// Generates worker/embedded.gen.ts: the scripts the Lab uploads into boxes, as strings.
import { readFileSync, writeFileSync } from "node:fs";

const files = { RUN_PY: "boxes/run.py", VOTE_PY: "boxes/vote.py", SUITE_TS: "boxes/suite.ts", PORTAL_TS: "portal/server.ts" };
const body = Object.entries(files)
  .map(([name, path]) => `export const ${name} = ${JSON.stringify(readFileSync(path, "utf8"))};`)
  .join("\n");
writeFileSync("worker/embedded.gen.ts", `// Generated by scripts/embed.ts. Do not edit.\n${body}\n`);
